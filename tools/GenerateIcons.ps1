# Offline antialiased masks; no runtime graphics dependency.
Add-Type -AssemblyName System.Drawing
$output=[Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by tools/GenerateIcons.ps1; 4-bit coverage.')
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <Arduino.h>')
[void]$output.AppendLine('namespace SmoothIcons {')
$preview=[Drawing.Bitmap]::new(120,40)
$pg=[Drawing.Graphics]::FromImage($preview)
$pg.Clear([Drawing.Color]::FromArgb(24,0,74))
$index=0
foreach($name in @('settings','refresh','plate')) {
  $size=if($name -eq 'plate'){36}else{24}
  $bitmap=[Drawing.Bitmap]::new($size*8,$size*8)
  $g=[Drawing.Graphics]::FromImage($bitmap)
  $g.Clear([Drawing.Color]::Black)
  $g.SmoothingMode=[Drawing.Drawing2D.SmoothingMode]::AntiAlias
  $g.ScaleTransform(8,8)
  $pen=[Drawing.Pen]::new([Drawing.Color]::White,2.2)
  $pen.StartCap=[Drawing.Drawing2D.LineCap]::Round
  $pen.EndCap=[Drawing.Drawing2D.LineCap]::Round
  $pen.LineJoin=[Drawing.Drawing2D.LineJoin]::Round
  if($name -eq 'settings') {
    $points=[Drawing.PointF[]]::new(32)
    for($i=0;$i -lt 32;$i++) {
      $angle=$i*[Math]::PI/16
      $radius=if($i%4 -in @(1,2)){9.2}else{7.4}
      $points[$i]=[Drawing.PointF]::new(12+$radius*[Math]::Cos($angle),12+$radius*[Math]::Sin($angle))
    }
    $g.DrawPolygon($pen,$points)
    $g.DrawEllipse($pen,8.6,8.6,6.8,6.8)
  } elseif($name -eq 'refresh') {
    $g.DrawArc($pen,4,4,16,16,-135,270)
    $tip=[Drawing.PointF]::new(6.343,17.657)
    $g.DrawLine($pen,[Drawing.PointF]::new(6.343,22),$tip)
    $g.DrawLine($pen,$tip,[Drawing.PointF]::new(10.686,17.657))
  } else { $g.FillEllipse([Drawing.Brushes]::White,1,1,34,34) }
  $bytes=[Collections.Generic.List[byte]]::new()
  for($i=0;$i -lt $size*$size;$i++) {
    $px=$i%$size; $py=[int][Math]::Floor($i/$size); $sum=0
    for($sy=0;$sy -lt 8;$sy++){for($sx=0;$sx -lt 8;$sx++){
      $sum+=$bitmap.GetPixel($px*8+$sx,$py*8+$sy).R
    }}
    $a=[int][Math]::Round($sum*15/(64*255))
    if($i%2 -eq 0){$pending=$a -shl 4}else{$bytes.Add([byte]($pending -bor $a))}
    $preview.SetPixel($index*40+$px,$py,[Drawing.Color]::FromArgb([int](24+231*$a/15),[int](255*$a/15),[int](74+181*$a/15)))
  }
  [void]$output.AppendLine("static const uint8_t $name"+'[] PROGMEM = {')
  for($i=0;$i -lt $bytes.Count;$i+=24){
    $last=[Math]::Min($i+23,$bytes.Count-1)
    [void]$output.AppendLine((($bytes[$i..$last] | ForEach-Object {'0x{0:X2}' -f $_}) -join ',')+',')
  }
  [void]$output.AppendLine('};')
  $pen.Dispose();$g.Dispose();$bitmap.Dispose();$index++
}
[void]$output.AppendLine('} // namespace SmoothIcons')
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '../SmoothIconsData.h'),$output.ToString())
$preview.Save((Join-Path $PSScriptRoot 'icons-preview.png'))
$pg.Dispose();$preview.Dispose()
