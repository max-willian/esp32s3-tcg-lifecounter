# Offline Windows generator. Segoe UI Bold matches the life digits.
Add-Type -AssemblyName System.Drawing
$labels = @(
  @('SWU',16), @('MAGIC',16), @('CONFIGURACOES',16),
  @('PV JOGADOR 1',16), @('PV JOGADOR 2',16), @('JOGO: SWU',16), @('JOGO: MAGIC',16),
  @('VOLTAR',16), @('SALVAR',16), @('CERTEZA?',22),
  @('RESTAURAR PV?',12), @('RESTAURAR AMBOS?',12), @('SIM',16), @('NAO',16), @('3 SEGUNDOS',12),
  @('JOGADORES',16), @('JOGADORES: 1',16), @('JOGADORES: 2',16),
  @('1',16), @('2',16), @('3',16), @('4',16),
  @('nao implementado',16), @('<',16), @('>',16), @('2/2',12),
  @('P1',12), @('P2',12), @('SWU',12), @('MAGIC',12)
)
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by tools/GenerateText.ps1; 4-bit Segoe UI Bold label masks.')
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <Arduino.h>')
[void]$output.AppendLine('namespace SmoothText {')
$family = [Drawing.FontFamily]::new('Segoe UI')
$metadata = [Collections.Generic.List[string]]::new()
$preview = [Drawing.Bitmap]::new(240,($labels.Count*30))
$previewGraphics = [Drawing.Graphics]::FromImage($preview)
$previewGraphics.Clear([Drawing.Color]::FromArgb(24,0,74))
$index = 0
foreach ($label in $labels) {
  $text = [string]$label[0]; $height = [int]$label[1]
  $path = [Drawing.Drawing2D.GraphicsPath]::new()
  $path.AddString($text,$family,1,100,[Drawing.PointF]::new(0,0),[Drawing.StringFormat]::GenericTypographic)
  $bounds = $path.GetBounds()
  $scale = ($height-2)/$bounds.Height
  $width = [int][Math]::Ceiling($bounds.Width*$scale)+2
  $matrix = [Drawing.Drawing2D.Matrix]::new()
  $matrix.Translate(-$bounds.X,-$bounds.Y)
  $path.Transform($matrix)
  $matrix.Reset(); $matrix.Scale($scale*4,$scale*4); $path.Transform($matrix)
  $matrix.Reset(); $matrix.Translate(4,4); $path.Transform($matrix)
  $bitmap = [Drawing.Bitmap]::new($width*4,$height*4)
  $graphics = [Drawing.Graphics]::FromImage($bitmap)
  $graphics.Clear([Drawing.Color]::Black)
  $graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
  $graphics.FillPath([Drawing.Brushes]::White,$path)
  $bytes = [Collections.Generic.List[byte]]::new()
  $pending = 0
  for ($i=0;$i -lt $width*$height;$i++) {
    $px=$i%$width; $py=[int][Math]::Floor($i/$width); $sum=0
    for($sy=0;$sy -lt 4;$sy++) { for($sx=0;$sx -lt 4;$sx++) {
      $sum += $bitmap.GetPixel($px*4+$sx,$py*4+$sy).R
    }}
    $a=[int][Math]::Round($sum*15/(16*255))
    if($i%2 -eq 0) { $pending=$a -shl 4 } else { $bytes.Add([byte]($pending -bor $a)) }
    $preview.SetPixel([int]((240-$width)/2)+$px,$index*30+$py,
      [Drawing.Color]::FromArgb([int](24+231*$a/15),[int](255*$a/15),[int](74+181*$a/15)))
  }
  if(($width*$height)%2 -ne 0) { $bytes.Add([byte]$pending) }
  [void]$output.AppendLine("static const uint8_t label$index"+'[] PROGMEM = {')
  for($i=0;$i -lt $bytes.Count;$i+=24) {
    $last=[Math]::Min($i+23,$bytes.Count-1)
    [void]$output.AppendLine((($bytes[$i..$last] | ForEach-Object {'0x{0:X2}' -f $_}) -join ',')+',')
  }
  [void]$output.AppendLine('};')
  $metadata.Add('{"'+$text+'",'+$width+','+$height+',label'+$index+'},')
  $graphics.Dispose();$bitmap.Dispose();$path.Dispose();$matrix.Dispose()
  $index++
}
[void]$output.AppendLine('struct Label { const char *text; uint16_t width; uint8_t height; const uint8_t *data; };')
[void]$output.AppendLine('static const Label labels[] = {')
foreach($entry in $metadata) {[void]$output.AppendLine($entry)}
[void]$output.AppendLine('};')
[void]$output.AppendLine('} // namespace SmoothText')
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '../SmoothTextData.h'),$output.ToString())
$preview.Save((Join-Path $PSScriptRoot 'text-preview.png'))
$previewGraphics.Dispose();$preview.Dispose();$family.Dispose()
