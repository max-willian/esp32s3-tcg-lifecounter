# Offline asset generation on Windows; not needed to compile the sketch.
Add-Type -AssemblyName System.Drawing
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by tools/GenerateDigits.ps1. Segoe UI Bold digit coverage, 4 bits/pixel.')
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <Arduino.h>')
[void]$output.AppendLine('namespace SmoothDigits {')
$family = [Drawing.FontFamily]::new('Segoe UI')
$sizes = @(56,40,28,18,12,10)
$widths = @()
foreach ($height in $sizes) {
  $width = [int][Math]::Ceiling($height * 0.8) + 2
  $widths += $width
  $bytes = [Collections.Generic.List[byte]]::new()
  foreach ($digit in 0..9) {
    $path = [Drawing.Drawing2D.GraphicsPath]::new()
    $path.AddString([string]$digit,$family,1,100,[Drawing.PointF]::new(0,0),[Drawing.StringFormat]::GenericTypographic)
    $bounds = $path.GetBounds()
    $scale = ($height - 2) / $bounds.Height
    $matrix = [Drawing.Drawing2D.Matrix]::new()
    $matrix.Translate(-$bounds.X,-$bounds.Y)
    $path.Transform($matrix)
    $matrix.Reset()
    $matrix.Scale($scale*4,$scale*4)
    $path.Transform($matrix)
    $matrix.Reset()
    $matrix.Translate(($width*4-$bounds.Width*$scale*4)/2,4)
    $path.Transform($matrix)
    $bitmap = [Drawing.Bitmap]::new($width*4,$height*4)
    $graphics = [Drawing.Graphics]::FromImage($bitmap)
    $graphics.Clear([Drawing.Color]::Black)
    $graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $graphics.FillPath([Drawing.Brushes]::White,$path)
    $pending = 0
    for ($i=0; $i -lt $width*$height; $i++) {
      $px = $i % $width; $py = [int][Math]::Floor($i/$width)
      $sum=0
      for ($sy=0;$sy -lt 4;$sy++) { for ($sx=0;$sx -lt 4;$sx++) {
        $sum += $bitmap.GetPixel($px*4+$sx,$py*4+$sy).R
      }}
      $coverage = [int][Math]::Round($sum*15/(16*255))
      if ($i%2 -eq 0) { $pending=$coverage -shl 4 }
      else { $bytes.Add([byte]($pending -bor $coverage)) }
    }
    if (($width*$height)%2 -ne 0) { $bytes.Add([byte]$pending) }
    $graphics.Dispose(); $bitmap.Dispose(); $path.Dispose(); $matrix.Dispose()
  }
  [void]$output.AppendLine("static const uint8_t digits$height"+'[] PROGMEM = {')
  for ($i=0;$i -lt $bytes.Count;$i+=24) {
    $last=[Math]::Min($i+23,$bytes.Count-1)
    [void]$output.AppendLine((($bytes[$i..$last] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ',')+',')
  }
  [void]$output.AppendLine('};')
}
[void]$output.AppendLine('struct Face { uint8_t width, height; const uint8_t *data; };')
[void]$output.AppendLine('static const Face faces[] = {')
for ($i=0;$i -lt $sizes.Count;$i++) {
  [void]$output.AppendLine("{$($widths[$i]),$($sizes[$i]),digits$($sizes[$i])},")
}
[void]$output.AppendLine('};')
[void]$output.AppendLine('} // namespace SmoothDigits')
$family.Dispose()
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '../SmoothDigitsData.h'),$output.ToString())
