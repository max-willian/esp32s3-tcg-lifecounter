# Convert the supplied GIF offline; Arduino needs only the generated C++ assets.
Add-Type -AssemblyName System.Drawing
$root=Split-Path $PSScriptRoot
$gif=[Drawing.Image]::FromFile((Join-Path $root 'assets/hyperspace.gif'))
$dimension=[Drawing.Imaging.FrameDimension]::new($gif.FrameDimensionsList[0])
$frameCount=$gif.GetFrameCount($dimension)
$delays=$gif.GetPropertyItem(0x5100).Value
$step=3
$count=[int][Math]::Ceiling($frameCount/$step)
$out=[Text.StringBuilder]::new()
[void]$out.AppendLine('// Generated by tools/GenerateBackground.ps1 from assets/hyperspace.gif.')
[void]$out.AppendLine('#include "HyperspaceData.h"')
[void]$out.AppendLine('namespace Hyperspace {')
$palette=@()
foreach($i in 0..15){
  $t=$i/15
  # Dim highlights to protect yellow PV contrast; retain the navy tint.
  $r=[int](5+175*$t);$g=[int](3+177*$t);$b=[int](16+179*$t)
  $palette+= (($r -shr 3) -shl 11) -bor (($g -shr 2) -shl 5) -bor ($b -shr 3)
}
[void]$out.AppendLine('const uint16_t palette[16] PROGMEM = {'+(($palette | ForEach-Object {'0x{0:X4}' -f $_}) -join ',')+'};')
$durations=@()
[void]$out.AppendLine('const uint8_t frames[] PROGMEM = {')
for($frame=0;$frame -lt $frameCount;$frame+=$step){
  $duration=0
  for($j=$frame;$j -lt [Math]::Min($frame+$step,$frameCount);$j++){
    $duration += [Math]::Max(10,[BitConverter]::ToInt32($delays,$j*4)*10)
  }
  $durations+=$duration
  $gif.SelectActiveFrame($dimension,$frame) | Out-Null
  $bitmap=[Drawing.Bitmap]::new(240,240)
  $g=[Drawing.Graphics]::FromImage($bitmap)
  $g.InterpolationMode=[Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  # The original is letterboxed: image content is y=72..527. Center square crop.
  $g.DrawImage($gif,[Drawing.Rectangle]::new(0,0,240,240),172,72,456,456,[Drawing.GraphicsUnit]::Pixel)
  $bytes=[byte[]]::new(28800)
  for($i=0;$i -lt 57600;$i++){
    $x=$i%240;$y=[int][Math]::Floor($i/240)
    $pixel=$bitmap.GetPixel($x,$y)
    $level=[int][Math]::Round((0.2126*$pixel.R+0.7152*$pixel.G+0.0722*$pixel.B)*15/255)
    $index=[int][Math]::Floor($i/2)
    if($i%2 -eq 0){$bytes[$index]=$level -shl 4}else{$bytes[$index]=$bytes[$index] -bor $level}
    if($frame -eq 0){
      $rgb=$palette[$level]
      $bitmap.SetPixel($x,$y,[Drawing.Color]::FromArgb([int](($rgb -shr 11 -band 31)*255/31),[int](($rgb -shr 5 -band 63)*255/63),[int](($rgb -band 31)*255/31)))
    }
  }
  if($frame -eq 0){$bitmap.Save((Join-Path $root 'assets/background-preview.png'))}
  for($i=0;$i -lt $bytes.Length;$i+=32){
    $last=[Math]::Min($i+31,$bytes.Length-1)
    [void]$out.AppendLine((($bytes[$i..$last] | ForEach-Object {'0x{0:X2}' -f $_}) -join ',')+',')
  }
  $g.Dispose();$bitmap.Dispose()
}
[void]$out.AppendLine('};')
[void]$out.AppendLine('const uint16_t durations[FRAME_COUNT] PROGMEM = {'+($durations -join ',')+'};')
[void]$out.AppendLine('} // namespace Hyperspace')
[IO.File]::WriteAllText((Join-Path $root 'HyperspaceData.cpp'),$out.ToString())
$header=@"
// Generated by tools/GenerateBackground.ps1.
#pragma once
#include <Arduino.h>
namespace Hyperspace {
constexpr uint8_t FRAME_COUNT = $count;
constexpr uint32_t FRAME_BYTES = 28800;
extern const uint16_t palette[16] PROGMEM;
extern const uint8_t frames[FRAME_COUNT * FRAME_BYTES] PROGMEM;
extern const uint16_t durations[FRAME_COUNT] PROGMEM;
}
"@
[IO.File]::WriteAllText((Join-Path $root 'HyperspaceData.h'),$header)
$gif.Dispose()
"Generated $count frames; $($count*28800) bytes; loop $((($durations | Measure-Object -Sum).Sum)) ms."
